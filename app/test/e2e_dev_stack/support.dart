/// The throwaway stack the scenarios run against. Null (every file then skips) unless scripts/dev/dev-stack.sh
/// started the flutter container (E2E_DEV_STACK=1), so a plain `flutter test` never needs a server.
class DevEnv {
  DevEnv._(this.e2e, this.ownerEmail, this.ownerPassword, this.stateDir, this.dbMaxConns, this.pgComposeCommand);

  final E2eEnv e2e;
  final String ownerEmail;
  final String ownerPassword;
  final String stateDir;
  final int dbMaxConns;

  /// The command docker-compose.yml gives the postgres service, as `docker compose config` renders it for this
  /// stack (dev-stack.sh passes it in). The connection-limit scenario reads the limit from HERE, so it checks
  /// the repo's own compose file and not a number the stack scripts also wrote.
  final String pgComposeCommand;

  static DevEnv? fromEnvironment() {
    final Map<String, String> e = Platform.environment;
    if (e['E2E_DEV_STACK'] != '1') return null;
    final E2eEnv? base = E2eEnv.fromEnvironment();
    if (base == null) return null;
    // Defence in depth: the scenarios write to the database and create accounts. The scripts always pass the
    // throwaway stack's own values; anything else (a hand-set URL, a sourced production .env) is refused.
    requireLoopbackUrl('E2E_BASE_URL', base.base);
    requireLoopbackUrl('E2E_DATABASE_URL', base.dbUrl);
    final String stateDir = e['E2E_STATE_DIR'] ?? '/state';
    final File marker = File('$stateDir/stack.env');
    if (!marker.existsSync() || !marker.readAsStringSync().startsWith('# Generated by scripts/dev/dev-stack.sh. Throwaway secrets')) {
      throw StateError('$stateDir/stack.env is not a scripts/dev/dev-stack.sh throwaway stack file: refusing to run against an unknown target');
    }
    return DevEnv._(base, e['E2E_OWNER_EMAIL'] ?? '', e['E2E_OWNER_PASSWORD'] ?? '', stateDir,
        int.tryParse(e['E2E_DB_MAX_CONNS'] ?? '') ?? 15, e['E2E_PG_COMPOSE_COMMAND'] ?? '');
  }

  String get base => e2e.base;
}

