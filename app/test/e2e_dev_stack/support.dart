/// Per-item verdicts of a batch answer: seq -> status/error.
List<Map<String, dynamic>> batchResults(Resp r) =>
    ((r.json['results'] as List<dynamic>?) ?? <dynamic>[]).map((dynamic e) => e as Map<String, dynamic>).toList();

/// Marks a check that DEPENDS ON A FEATURE STILL BEING BUILT. It runs the check and requires that its
/// EXPECTATION fails today (a [TestFailure], i.e. an `expect` that does not hold). Any other error (a timeout, an
/// HTTP/API exception, a null, a missing precondition) is a broken set-up, not a missing feature, and fails the
/// test with its own error instead of passing as "still failing". The day the feature lands the check passes,
/// this test fails with "now passes" and the marker is removed (turning it into a real check). E2E_XFAIL=skip
/// skips them instead of running them. Put the set-up and the preconditions BEFORE the first `expect` on the
/// feature and use [precondition] for them, so only the feature's own assertion can count as expected.
void expectedFailing(String name, String reason, Future<void> Function() body) {
  test('EXPECTED-FAILING $name', () async {
    TestFailure? failure;
    try {
      await body();
    } on TestFailure catch (e) {
      failure = e;
    }
    if (failure == null) {
      fail('"$name" now PASSES: the feature ($reason) has landed. Delete expectedFailing(...) and keep the check as a real test.');
    }
    // ignore: avoid_print
    print('EXPECTED-FAILING (still): $name -- waiting for: $reason');
    // ignore: avoid_print
    print('    fails today with: ${failure.toString().split('\n').first}');
  }, skip: Platform.environment['E2E_XFAIL'] == 'skip' ? 'EXPECTED-FAILING, skipped by E2E_XFAIL=skip: $reason' : false);
}

/// A condition the expected-failing check relies on that must hold with and without the feature. Throws a
/// [StateError] (not a [TestFailure]), so [expectedFailing] reports a broken set-up instead of "still failing".
void precondition(bool ok, String what) {
  if (!ok) throw StateError('precondition of the check does not hold: $what');
}

