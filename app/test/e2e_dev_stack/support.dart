/// An HTTP answer with its status (the harness `rawJson` throws on non-2xx; the scenarios assert on refusals).
class Resp {
  Resp(this.status, this.body);
  final int status;
  final String body;

  Map<String, dynamic> get json {
    if (body.isEmpty) return <String, dynamic>{};
    final Object? d = jsonDecode(body);
    return d is Map<String, dynamic> ? d : <String, dynamic>{'_list': d};
  }

  /// The machine code of a refusal (`{"error":..., "code":...}`), or ''.
  String get code => (json['code'] as String?) ?? '';

  @override
  String toString() => '$status $body';
}

final http.Client _plain = http.Client();

Future<Resp> call(DevEnv env, String method, String path, {Object? body, String? token, String? ip, Map<String, String>? headers}) async {
  final http.Request r = http.Request(method, Uri.parse('${env.base}$path'));
  r.headers['Content-Type'] = 'application/json';
  if (token != null) r.headers['Authorization'] = 'Bearer $token';
  if (ip != null && ip.isNotEmpty) r.headers['X-Forwarded-For'] = ip;
  if (headers != null) r.headers.addAll(headers);
  if (body != null) r.body = jsonEncode(body);
  final http.Response res = await http.Response.fromStream(await _plain.send(r).timeout(const Duration(seconds: 30)));
  return Resp(res.statusCode, res.body);
}

final Random _rng = Random();
int _ipCounter = _rng.nextInt(200);

/// A public-looking client address (documentation ranges) for X-Forwarded-For: the stack trusts the header from
/// the docker bridge, and the per-IP auth limits then count each simulated phone separately. A private address
/// would be skipped by the proxy logic, so these must not be 10.x / 192.168.x / 172.16.x.
String nextIp() {
  _ipCounter++;
  const List<String> nets = <String>['203.0.113', '198.51.100', '192.0.2'];
  return '${nets[(_ipCounter ~/ 250) % nets.length]}.${1 + _ipCounter % 250}';
}

final String stamp = DateTime.now().millisecondsSinceEpoch.toString();
const String userPassword = 'correct horse battery staple';

/// Admin side of the stack: signs the owner in and makes ordinary accounts through the real admin API
/// (no /auth/register, whose 5 per hour per address limit would cap the number of test accounts).
class DevStack {
  DevStack(this.env);
  final DevEnv env;
  String? _ownerToken;
  String? _ownerId;
  final String ownerIp = nextIp();

  Future<String> ownerToken() async {
    if (_ownerToken != null) return _ownerToken!;
    final Map<String, dynamic> login = await rawJson(env.e2e, 'POST', '/auth/login',
        body: <String, dynamic>{'email': env.ownerEmail, 'password': env.ownerPassword}, ip: ownerIp);
    _ownerToken = login['access_token'] as String;
    return _ownerToken!;
  }

  Future<String> ownerId() async {
    if (_ownerId != null) return _ownerId!;
    final Map<String, dynamic> me = await rawJson(env.e2e, 'GET', '/me', token: await ownerToken(), ip: ownerIp);
    _ownerId = (me['id'] ?? (me['user'] as Map<String, dynamic>)['id']) as String;
    return _ownerId!;
  }

  /// The platform admin account from the stack's own secrets file (PLATFORM_ADMIN_EMAIL), as a phone.
  Future<Phone> ownerPhone(String name) async {
    final Phone p = Phone(name, env.ownerEmail, env.ownerPassword)..ip = nextIp();
    await p.loginExisting(env.e2e, await ownerId());
    p.startRuntime();
    return p;
  }

  /// A new ordinary account (admin-created), signed in, with its own client address.
  Future<Phone> newUser(String name, {String? familyId, bool runtime = true, String? email, String password = userPassword}) async {
    email ??= '${name.toLowerCase()}-$stamp-${_rng.nextInt(1 << 20)}@dev.orbitly.test';
    final Map<String, dynamic> made = await rawJson(env.e2e, 'POST', '/api/admin/users',
        body: <String, dynamic>{'email': email, 'password': password, 'name': name, 'role': 'member', if (familyId != null) 'family_id': familyId},
        token: await ownerToken(), ip: ownerIp);
    final Phone p = Phone(name, email, password)..ip = nextIp();
    await p.loginExisting(env.e2e, made['id'] as String);
    if (runtime) p.startRuntime();
    return p;
  }

  /// Owner creates a circle, members join it by invite. Returns the circle id.
  Future<String> createCircle(Phone owner, List<Phone> members, {String name = 'Dev circle'}) async {
    final Map<String, dynamic> created = await rawJson(env.e2e, 'POST', '/circles', body: <String, dynamic>{'name': name}, token: owner.token, ip: owner.ip);
    final String circle = (created['id'] ?? (created['circle'] as Map<String, dynamic>)['id']) as String;
    final Map<String, dynamic> inv = await rawJson(env.e2e, 'POST', '/circles/$circle/invites',
        body: <String, dynamic>{'role': 'member', 'max_uses': 10, 'expires_in_hours': 24}, token: owner.token, ip: owner.ip);
    final String code = (inv['code'] ?? (inv['invite'] as Map<String, dynamic>)['code']) as String;
    for (final Phone m in members) {
      await rawJson(env.e2e, 'POST', '/circles/join', body: <String, dynamic>{'code': code}, token: m.token, ip: m.ip);
    }
    return circle;
  }

  /// Every phone registers its key (with the lanes capability), the owner turns the circle Private, members
  /// pick up the circle key, every runtime learns the circle. Uses the app's own E2eeService.
  Future<void> makePrivate(String circle, Phone owner, List<Phone> members) async {
    for (final Phone p in <Phone>[owner, ...members]) {
      await p.run(() => p.service.registerThisDevice());
    }
    await owner.run(() => owner.service.enableCircle(circle));
    for (final Phone m in members) {
      await m.run(() => m.service.syncCircleKeys(circle));
    }
    for (final Phone p in <Phone>[owner, ...members]) {
      await p.syncCircle(circle);
    }
  }
}

/// The app's "Add server" flow on [owner]'s phone: approve the built-in server's key, switch the policy on and put the
/// owner on the server lane. Approving makes the server write its identity file (fsync) before it answers, which
/// can take longer than the app's 15 second request limit on a busy disk. The app would show an error and the
/// person would tap OK again; this does the same: on a timeout it waits for the server to finish and runs the
/// flow once more.
Future<void> addServerThroughApp(Phone owner, String circle, {Duration patience = const Duration(minutes: 2)}) async {
  final AddServerFlow flow = AddServerFlow(LanesProcessingController(owner.lanes));
  AddServerPlan plan = await owner.run(() => flow.plan(circle));
  expect(plan.state, AddServerState.approveServer, reason: 'a fresh stack: the built-in server device is waiting for approval');
  try {
    await owner.run(() => flow.confirm(circle, plan));
    return;
  } on ApiException catch (e) {
    if (e.status != 0) rethrow; // only "the request timed out"
    // ignore: avoid_print
    print('addServerThroughApp: the approval timed out, waiting for the server to finish ($e)');
  }
  final DateTime end = DateTime.now().add(patience);
  while ((await owner.run(() => const ApiE2eeApi().serverJoin())).waiting && DateTime.now().isBefore(end)) {
    await Future<void>.delayed(const Duration(seconds: 2));
  }
  plan = await owner.run(() => flow.plan(circle));
  await owner.run(() => flow.confirm(circle, plan));
}

/// The API container's log (scripts/dev/e2e.sh streams `docker logs -f` into <state>/logs/api.log).
class LogTail {
  LogTail(DevEnv env, String name) : file = File('${env.stateDir}/logs/$name.log');
  final File file;

  bool get available => file.existsSync();

  /// Call before the action; pass the result to [since] / [waitFor].
  int mark() => available ? file.lengthSync() : 0;

  String since(int mark) {
    if (!available) return '';
    final Uint8List all = file.readAsBytesSync();
    return utf8.decode(all.sublist(min(mark, all.length)), allowMalformed: true);
  }

  /// Waits until the log file stopped growing for [quiet] (the `docker logs -f` stream caught up).
  Future<void> settle({Duration quiet = const Duration(seconds: 2), Duration timeout = const Duration(seconds: 30)}) async {
    final DateTime end = DateTime.now().add(timeout);
    int last = mark();
    DateTime since = DateTime.now();
    while (DateTime.now().isBefore(end)) {
      await Future<void>.delayed(const Duration(milliseconds: 250));
      final int now = mark();
      if (now != last) {
        last = now;
        since = DateTime.now();
      } else if (DateTime.now().difference(since) >= quiet) {
        return;
      }
    }
  }

  /// Lines (after [mark]) that contain every fragment; waits up to [timeout] for the log stream to catch up.
  Future<List<String>> waitFor(int mark, List<String> fragments, {Duration timeout = const Duration(seconds: 15)}) async {
    final DateTime end = DateTime.now().add(timeout);
    while (true) {
      final List<String> hit = since(mark).split('\n').where((String l) => fragments.every(l.contains)).toList();
      if (hit.isNotEmpty || !DateTime.now().isBefore(end)) return hit;
      await Future<void>.delayed(const Duration(milliseconds: 300));
    }
  }
}

void requireLogs(LogTail log) {
  if (!log.available) {
    throw StateError('${log.file.path} is missing: run this through scripts/dev/e2e.sh, which streams the container logs there');
  }
}

/// A sealed-looking item the server must refuse. The server never decrypts, so for the checks that happen
/// BEFORE the ciphertext matters (device state, epoch, lane) random bytes under a valid header are enough.
/// [line] 'server' makes a v2 item (line + generation in the header); '' makes a v1 phone item.
Map<String, dynamic> craftItem({required int epoch, String line = '', String purpose = 'fix'}) {
  const int bucket = 256;
  final Random r = Random.secure();
  final int seq = 1000000 + r.nextInt(1 << 30);
  final Uint8List ct;
  if (line == 'server') {
    ct = Uint8List(1 + 1 + 4 + 24 + bucket + 16);
    ct[0] = E2ee.msgVersionV2;
    ct[1] = E2ee.lineServer;
    ct.buffer.asByteData().setUint32(2, epoch);
  } else {
    ct = Uint8List(1 + 4 + 24 + bucket + 16);
    ct[0] = E2ee.msgVersion;
    ct.buffer.asByteData().setUint32(1, epoch);
  }
  for (int i = 0; i < ct.length; i++) {
    if (i > 5) ct[i] = r.nextInt(256);
  }
  return <String, dynamic>{
    'seq': seq,
    'purpose': purpose,
    'epoch': epoch,
    'size_bucket': bucket,
    'ciphertext': base64.encode(ct),
    if (line.isNotEmpty) 'key_line': line,
  };
}

/// POST /circles/{id}/e2ee/batch as [p] from device [deviceId] (the phone's own, or an old one).
