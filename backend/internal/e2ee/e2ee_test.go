func TestFingerprintFormats(t *testing.T) {
	a := mk(t, 1)
	fp, _ := Fingerprint(a.ed, a.x)
	if len(fp) != 32 {
		t.Fatal("fingerprint size")
	}
	if !regexp.MustCompile(`^(\d{5} ){11}\d{5}$`).MatchString(DigitGroups(fp)) {
		t.Fatalf("digits %q", DigitGroups(fp))
	}
	if !regexp.MustCompile(`^([0-9A-F]{4} ){3}[0-9A-F]{4}$`).MatchString(ShortFingerprint(fp)) {
		t.Fatalf("short %q", ShortFingerprint(fp))
	}
	b := mk(t, 2)
	fp2, _ := Fingerprint(b.ed, b.x)
	if DigitGroups(fp) == DigitGroups(fp2) {
		t.Fatal("distinct keys produced equal digits")
	}
	// Swapping the two keys changes the fingerprint (order is part of the encoding).
	fp3, _ := Fingerprint(a.x, a.ed)
	if bytes.Equal(fp, fp3) {
		t.Fatal("fingerprint ignores key order")
	}
}

func TestSafetyNumberSymmetricAndSensitive(t *testing.T) {
	a, b := mk(t, 1), mk(t, 2)
	fa, _ := Fingerprint(a.ed, a.x)
	fb, _ := Fingerprint(b.ed, b.x)
	ab := SafetyNumber(uidA, [][]byte{fa}, uidB, [][]byte{fb})
	ba := SafetyNumber(uidB, [][]byte{fb}, uidA, [][]byte{fa})
	if ab != ba {
		t.Fatal("not symmetric")
	}
	c := mk(t, 3)
	fc, _ := Fingerprint(c.ed, c.x)
	if SafetyNumber(uidA, [][]byte{fa}, uidB, [][]byte{fc}) == ab {
		t.Fatal("peer key change not reflected")
	}
	// Order of a user's devices does not matter; membership does.
	x := SafetyNumber(uidA, [][]byte{fa, fc}, uidB, [][]byte{fb})
	y := SafetyNumber(uidA, [][]byte{fc, fa}, uidB, [][]byte{fb})
	if x != y || x == ab {
		t.Fatal("device set handling wrong")
	}
}

func TestBindingAndRotation(t *testing.T) {
	a, b := mk(t, 1), mk(t, 2)
	m, _ := BindingMessage(uidA, devA, a.ed, a.x)
	sig := ed25519.Sign(a.priv, m)
	if err := VerifyBinding(uidA, devA, a.ed, a.x, sig); err != nil {
		t.Fatal(err)
	}
	if VerifyBinding(uidB, devA, a.ed, a.x, sig) == nil {
		t.Fatal("binding replayed to another user")
	}
	if VerifyBinding(uidA, devA, a.ed, b.x, sig) == nil {
		t.Fatal("binding accepted with swapped x25519 key")
	}
	bad := append([]byte{}, sig...)
	bad[0] ^= 1
	if VerifyBinding(uidA, devA, a.ed, a.x, bad) == nil {
		t.Fatal("tampered signature accepted")
	}
	if VerifyBinding(uidA, devA, a.ed, a.x, sig[:10]) == nil {
		t.Fatal("short signature accepted")
	}
	if VerifyBinding("not-a-uuid", devA, a.ed, a.x, sig) == nil {
		t.Fatal("bad user id accepted")
	}
	// Signed by a different key.
	m2, _ := BindingMessage(uidA, devA, b.ed, a.x)
	if VerifyBinding(uidA, devA, b.ed, a.x, ed25519.Sign(a.priv, m2)) == nil {
		t.Fatal("signature by other key accepted")
	}
	if VerifyBinding(uidA, devB, a.ed, a.x, sig) == nil {
		t.Fatal("binding replayed under another device id")
	}
	fpB, _ := Fingerprint(b.ed, b.x)
	lm, _ := LogActionMessage(ActRotate, uidA, devA, "", devB, 0, fpB)
	ls := ed25519.Sign(a.priv, lm)
	if err := VerifyLogAction(a.ed, ActRotate, uidA, devA, "", devB, 0, fpB, ls); err != nil {
		t.Fatal(err)
	}
	if VerifyLogAction(a.ed, ActRevoke, uidA, devA, "", devB, 0, fpB, ls) == nil {
		t.Fatal("signature replayed as another action")
	}
	if VerifyLogAction(a.ed, ActRotate, uidB, devA, "", devB, 0, fpB, ls) == nil {
		t.Fatal("signature replayed for another user")
	}
	if VerifyLogAction(a.ed, ActRotate, uidA, devA, circ, devB, 0, fpB, ls) == nil {
		t.Fatal("circle not bound")
	}
	if VerifyLogAction(b.ed, ActRotate, uidA, devA, "", devB, 0, fpB, ls) == nil {
		t.Fatal("wrong actor key accepted")
	}
}

func TestLogChainDetectsTampering(t *testing.T) {
	a := mk(t, 1)
	var prev = GenesisHash
	var hashes [][]byte
	for i := uint64(1); i <= 3; i++ {
		m, _ := LogActionMessage(ActEpoch, uidA, devA, circ, "", uint32(i), nil)
		sig := ed25519.Sign(a.priv, m)
		h := LogEntryHash(prev, i, m, sig)
		hashes = append(hashes, h)
		prev = h
	}
	// Recompute with entry 2 rewritten: entry 3's hash must change.
	m2, _ := LogActionMessage(ActEpoch, uidA, devA, circ, "", 99, nil)
	h2 := LogEntryHash(hashes[0], 2, m2, ed25519.Sign(a.priv, m2))
	m3, _ := LogActionMessage(ActEpoch, uidA, devA, circ, "", 3, nil)
	if bytes.Equal(LogEntryHash(h2, 3, m3, ed25519.Sign(a.priv, m3)), hashes[2]) {
		t.Fatal("rewriting history did not change the head")
	}
	if bytes.Equal(LogEntryHash(hashes[0], 3, m3, ed25519.Sign(a.priv, m3)), hashes[2]) {
		t.Fatal("dropping an entry did not change the head")
	}
}

func TestRecovery(t *testing.T) {
	ent := bytes.Repeat([]byte{0x7f}, 32)
	s0, _ := RecoverySeed(ent, "")
	s1, _ := RecoverySeed(ent, "pw")
	s2, _ := RecoverySeed(ent, "pw2")
	s3, _ := RecoverySeed(ent, "")
	if bytes.Equal(s0, s1) || bytes.Equal(s1, s2) || !bytes.Equal(s0, s3) {
		t.Fatal("passphrase handling wrong")
	}
	other, _ := RecoverySeed(bytes.Repeat([]byte{0x7e}, 32), "")
	if bytes.Equal(s0, other) {
		t.Fatal("entropy ignored")
	}
	e1, x1, _ := RecoveryIdentity(s0)
	if bytes.Equal(e1, x1) {
		t.Fatal("labels not domain separated")
	}
	if _, err := RecoverySeed(ent[:16], ""); err == nil {
		t.Fatal("short entropy accepted")
	}
	// A recovery wrap round trip with the derived X25519 key; tampering fails.
	xk, _ := ecdh.X25519().NewPrivateKey(x1)
	aad, _ := WrapAAD(circ, 1, devB, devA)
	blob, _ := Wrap(seed(9), xk.PublicKey().Bytes(), aad)
	if got, err := Unwrap(blob, x1, xk.PublicKey().Bytes(), aad); err != nil || !bytes.Equal(got, seed(9)) {
		t.Fatal("recovery unwrap failed")
	}
	wrongE, wrongX, _ := RecoveryIdentity(s1)
	_ = wrongE
	if _, err := Unwrap(blob, wrongX, xk.PublicKey().Bytes(), aad); err == nil {
		t.Fatal("wrong passphrase identity opened the wrap")
	}
	blob[60] ^= 1
	if _, err := Unwrap(blob, x1, xk.PublicKey().Bytes(), aad); err == nil {
		t.Fatal("tampered recovery wrap opened")
	}
}

func TestPadding(t *testing.T) {
	for _, n := range []int{0, 1, 100, 254, 255, 600, 1022, 4094, 5000} {
		p, err := Pad(bytes.Repeat([]byte{7}, n))
		if err != nil {
			t.Fatal(err)
		}
		if len(p) != PadBucket(n) || (len(p) != 256 && len(p) != 512 && len(p) != 1024 && len(p) != 4096 && len(p)%4096 != 0) {
			t.Fatalf("n=%d len=%d", n, len(p))
		}
		u, err := Unpad(p)
		if err != nil || len(u) != n {
			t.Fatalf("unpad n=%d: %v", n, err)
		}
	}
	p, _ := Pad([]byte("x"))
	p[100] = 1
	if _, err := Unpad(p); err == nil {
		t.Fatal("non-zero padding accepted")
	}
}

