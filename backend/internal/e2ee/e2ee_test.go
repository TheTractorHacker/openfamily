func TestWrapRoundTripAndBinding(t *testing.T) {
	a, b := mk(t, 1), mk(t, 2)
	ck := seed(0x33)
	aad, _ := WrapAAD(circ, 2, devB, devA)
	blob, err := Wrap(ck, b.x, aad)
	if err != nil || len(blob) != WrapBlobLen {
		t.Fatalf("wrap: %v len %d", err, len(blob))
	}
	got, err := Unwrap(blob, b.xSecret, b.x, aad)
	if err != nil || !bytes.Equal(got, ck) {
		t.Fatalf("unwrap: %v", err)
	}
	// Two wraps of the same key differ (fresh ephemeral + nonce).
	blob2, _ := Wrap(ck, b.x, aad)
	if bytes.Equal(blob, blob2) {
		t.Fatal("wrap is deterministic")
	}
	// Wrong recipient, wrong epoch, wrong circle, wrong wrapper all fail.
	if _, err := Unwrap(blob, a.xSecret, a.x, aad); err == nil {
		t.Fatal("wrong recipient opened blob")
	}
	for name, mod := range map[string][]byte{
		"epoch":   must(WrapAAD(circ, 3, devB, devA)),
		"circle":  must(WrapAAD("dddddddd-dddd-4ddd-8ddd-dddddddddddd", 2, devB, devA)),
		"wrapper": must(WrapAAD(circ, 2, devB, devB)),
		"recip":   must(WrapAAD(circ, 2, devA, devA)),
	} {
		if _, err := Unwrap(blob, b.xSecret, b.x, mod); err == nil {
			t.Fatalf("AAD mismatch (%s) not detected", name)
		}
	}
	tam := append([]byte{}, blob...)
	tam[len(tam)-1] ^= 1
	if _, err := Unwrap(tam, b.xSecret, b.x, aad); err == nil {
		t.Fatal("tampered blob opened")
	}
	// Signature check as the server does it.
	sm, _ := WrapSigMessage(circ, 2, devB, devA, blob)
	sig := ed25519.Sign(a.priv, sm)
	if err := VerifyWrapSignature(a.ed, circ, 2, devB, devA, blob, sig); err != nil {
		t.Fatal(err)
	}
	if VerifyWrapSignature(a.ed, circ, 3, devB, devA, blob, sig) == nil {
		t.Fatal("signature valid for other epoch (rollback)")
	}
	if VerifyWrapSignature(b.ed, circ, 2, devB, devA, blob, sig) == nil {
		t.Fatal("signature accepted under other key")
	}
	if _, err := WrapAAD(circ, 0, devB, devA); err == nil {
		t.Fatal("epoch 0 accepted")
	}
}

