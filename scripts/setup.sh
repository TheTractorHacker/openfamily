#!/usr/bin/env bash
# First-time setup: writes a .env with freshly generated secrets.
# Never overwrites an existing .env.
#
# Usage: ./scripts/setup.sh
#   Non-interactive: SITE_ADDRESS=... PLATFORM_ADMIN_EMAIL=... ./scripts/setup.sh
set -euo pipefail

cd "$(dirname "$0")/.."

if [ -e .env ]; then
  echo ".env already exists; leaving it untouched. Delete or rename it to run setup again." >&2
  exit 1
fi

rand_hex() { # $1 = bytes
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

ask() { # $1 = var name, $2 = prompt, $3 = default
  local name="$1" prompt="$2" default="$3" val
  val="${!name:-}"
  if [ -z "$val" ] && [ -t 0 ]; then
    read -r -p "$prompt [$default]: " val
  fi
  printf -v "$name" '%s' "${val:-$default}"
}

SITE_ADDRESS="${SITE_ADDRESS:-}"
PLATFORM_ADMIN_EMAIL="${PLATFORM_ADMIN_EMAIL:-}"
ask SITE_ADDRESS "Public address (domain such as openfamily.example.com, or :80 for plain HTTP on a trusted network)" ":80"
ask PLATFORM_ADMIN_EMAIL "Platform admin email (creates the first admin account)" ""

for v in SITE_ADDRESS PLATFORM_ADMIN_EMAIL; do
  case "${!v}" in *[[:space:]\'\"\$\`\\]*)
    echo "error: $v must not contain whitespace, quotes, \$, backticks or backslashes" >&2; exit 1;;
  esac
done

POSTGRES_PASSWORD="$(rand_hex 24)"
JWT_SECRET="$(rand_hex 32)"
ADMIN_PASSWORD="$(rand_hex 12)"

if [ "$SITE_ADDRESS" = ":80" ]; then
  app_env=development
  profiles=""
else
  app_env=production
  profiles="proxy"
fi

umask 077
{
  echo "# Generated by scripts/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private."
  echo "POSTGRES_PASSWORD=$POSTGRES_PASSWORD"
  echo "JWT_SECRET=$JWT_SECRET"
  echo "SITE_ADDRESS=$SITE_ADDRESS"
  echo "APP_ENV=$app_env"
  if [ "$app_env" = production ]; then
    echo "# Postgres is reachable only on the private compose network. See docs/self-hosting.md (Database TLS)."
    echo "DB_SSL_DISABLE_OK=true"
  fi
  echo "COMPOSE_PROFILES=$profiles"
  if [ -n "$PLATFORM_ADMIN_EMAIL" ]; then
    echo "PLATFORM_ADMIN_EMAIL=$PLATFORM_ADMIN_EMAIL"
    echo "PLATFORM_ADMIN_PASSWORD=$ADMIN_PASSWORD"
  fi
} >.env

echo "Wrote .env (mode 600)."
echo
if [ -n "$PLATFORM_ADMIN_EMAIL" ]; then
  echo "Admin login:  $PLATFORM_ADMIN_EMAIL"
  echo "Password:     $ADMIN_PASSWORD   (also stored in .env; change it after first login)"
  echo
fi
echo "Next steps:"
echo "  docker compose up -d"
if [ "$app_env" = production ]; then
  echo "  Point DNS for $SITE_ADDRESS at this host and open ports 80 and 443."
  echo "  Admin panel: https://$SITE_ADDRESS/admin/"
else
  echo "  Admin panel: http://localhost:8080/admin/ (or http://$SITE_ADDRESS/admin/ with COMPOSE_PROFILES=proxy)"
fi
echo "  Back up regularly: ./scripts/backup.sh     Upgrade: ./scripts/upgrade.sh"
